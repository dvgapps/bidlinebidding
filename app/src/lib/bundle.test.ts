import { existsSync, readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import type { Bundle } from '../types'
import { computeAllMetrics, hm } from './metrics'
import { defaultFilters, lineVisible } from './filter'


const path = new URL('../../../data/2701.json', import.meta.url)
// the generated bundle is company data and is not in the repository: without it these tests are skipped (e.g. on GitHub)
const have = existsSync(path)
const bundle = (have ? JSON.parse(readFileSync(path, 'utf8')) : null) as Bundle
const metrics = have ? computeAllMetrics(bundle) : new Map()

describe.skipIf(!have)('package 2701 (generated by tools/ingest)', () => {

  it('shows 274 captain-eligible lines, like BidPro and IPA', () => {
    expect(bundle.lines.filter((l) => lineVisible(l, defaultFilters))).toHaveLength(274)
  })

  it('classifies 38 international airports and treats Canada/Mexico as domestic', () => {
    const intl = Object.entries(bundle.airports).filter(([, a]) => a.intl)
    expect(intl).toHaveLength(38)
    for (const code of ['YWG', 'MTY', 'GDL', 'NLU', 'SJU', 'ANC', 'OGG', 'SDF']) expect(bundle.airports[code].intl).toBe(false)
    for (const code of ['CGN', 'HKG', 'SDQ', 'SYD']) expect(bundle.airports[code].intl).toBe(true)
    expect(Object.values(bundle.airports).every((a) => a.intl !== null)).toBe(true)
  })

  it('line 500: domestic turns only', () => {
    const m = metrics.get(500)!
    expect(m.intlPct).toBe(0)
    expect(hm('80:12')).toBe(m.ctPP[0])
    expect(m.doPrinted).toBe(26)
    expect(m.ddPrinted).toBe(25)
    expect(m.tripCount).toBe(25)
  })

  it('some lines are international and every percentage is within 0..1', () => {
    const vals = [...metrics.values()]
    expect(vals.filter((m) => (m.intlPct ?? 0) > 0).length).toBeGreaterThan(10)
    for (const m of vals) {
      for (const p of [m.intlPct ?? 0, m.satOffPct, m.sunOffPct, m.wkndOffPct]) {
        expect(p).toBeGreaterThanOrEqual(0)
        expect(p).toBeLessThanOrEqual(1)
      }
    }
  })

  it('hybrid VTO line 741: flying PP printed, VTO PP shown as 75:00', () => {
    const m = metrics.get(741)!
    expect(m.tcPP).toEqual([hm('83:47'), 4500])
    expect(m.payMin).toBe(hm('83:47')! + 4500)
    expect(m.daysOff).toBeGreaterThanOrEqual(28)
  })
})
